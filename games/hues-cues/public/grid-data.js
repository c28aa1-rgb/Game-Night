  /** [{ row, col, hex, name }] — the flat form everything else reads. */
  function cells() {
    var out = [];
    for (var r = 0; r < ROWS.length; r++) {
      var row = ROWS[r];
      for (var c = 0; c < COLS; c++) {
        out.push({ row: row, col: c + 1, hex: RAW[row][c][0], name: RAW[row][c][1] });
      }
    }
    return out;
  }

  function cell(row, col) {
    var entry = RAW[row] && RAW[row][col - 1];
    return entry ? { row: row, col: col, hex: entry[0], name: entry[1] } : null;
  }

